'use strict';
const { normalizeZoneName, resolveName, absoluteTarget, relativeName } = require('./dnsutil');

const TYPE_ORDER = ['NS', 'A', 'AAAA', 'CNAME', 'MX', 'TXT'];

// hostmaster@example.com -> hostmaster.example.com.
// 本地部分中的点按 RFC 1035 转义：john.doe@example.com -> john\.doe.example.com.
function emailToRname(email) {
  const e = String(email || '').trim();
  const at = e.lastIndexOf('@');
  if (at < 0) return e.replace(/\./g, '\\.') + '.';
  const local = e.slice(0, at).replace(/\./g, '\\.');
  const domain = e.slice(at + 1).toLowerCase().replace(/\.+$/, '');
  return `${local}.${domain}.`;
}

function escapeTxt(s) {
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

// TXT 按 255 字符拆分为多个 char-string（BIND 语法要求）
function txtToCharStrings(s) {
  const chunks = [];
  for (let i = 0; i < s.length; i += 255) {
    chunks.push(`"${escapeTxt(s.slice(i, i + 255))}"`);
  }
  return chunks.length ? chunks.join(' ') : '""';
}

function formatRdata(type, value, zone) {
  const v = String(value).trim();
  switch (type) {
    case 'NS':
    case 'CNAME':
      return absoluteTarget(v, zone);
    case 'MX': {
      const m = v.match(/^(\d+)\s+(\S+)$/);
      if (!m) return v;
      return `${Number(m[1])} ${absoluteTarget(m[2], zone)}`;
    }
    case 'TXT':
      return txtToCharStrings(v);
    default:
      return v;
  }
}

function pad(s, n) {
  s = String(s);
  return s.length >= n ? s : s + ' '.repeat(n - s.length);
}

// 生成符合 BIND master file 语法的区域文件内容
function generateZoneFile({ zone, settings, records, serial, generatedAt }) {
  const z = normalizeZoneName(zone);
  const now = generatedAt || new Date().toISOString();
  const lines = [];
  lines.push(';;');
  lines.push(`;; Zone file for ${z}.`);
  lines.push(`;; Generated by DNS Zone Console at ${now}`);
  lines.push(';;');
  lines.push(`$ORIGIN ${z}.`);
  lines.push(`$TTL ${settings.default_ttl}`);
  lines.push('');
  lines.push(`@   IN  SOA ${absoluteTarget(settings.primary_ns, z)} ${emailToRname(settings.admin_email)} (`);
  lines.push(`        ${serial} ; Serial`);
  lines.push(`        ${settings.soa_refresh} ; Refresh`);
  lines.push(`        ${settings.soa_retry} ; Retry`);
  lines.push(`        ${settings.soa_expire} ; Expire`);
  lines.push(`        ${settings.soa_minimum} ; Negative caching TTL`);
  lines.push(')');
  lines.push('');

  const sorted = [...records].sort((a, b) => {
    const ta = TYPE_ORDER.indexOf(String(a.type).toUpperCase());
    const tb = TYPE_ORDER.indexOf(String(b.type).toUpperCase());
    if (ta !== tb) return ta - tb;
    const fa = resolveName(a.name, z).fqdn || '';
    const fb = resolveName(b.name, z).fqdn || '';
    if (fa !== fb) {
      if (fa === z) return -1;
      if (fb === z) return 1;
      return fa < fb ? -1 : 1;
    }
    return String(a.value).localeCompare(String(b.value));
  });

  let lastType = null;
  for (const rec of sorted) {
    const type = String(rec.type).toUpperCase();
    if (type !== lastType) {
      lines.push(`;; ${type} records`);
      lastType = type;
    }
    const fqdn = resolveName(rec.name, z).fqdn;
    const ttl = rec.ttl === null || rec.ttl === undefined || rec.ttl === '' ? settings.default_ttl : Number(rec.ttl);
    lines.push(`${pad(relativeName(fqdn, z), 20)} ${pad(ttl, 7)} IN ${pad(type, 6)} ${formatRdata(type, rec.value, z)}`);
  }
  lines.push('');
  return lines.join('\n');
}

module.exports = { generateZoneFile, emailToRname, formatRdata };
