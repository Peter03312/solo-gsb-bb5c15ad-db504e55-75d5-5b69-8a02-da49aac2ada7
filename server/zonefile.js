'use strict';
// BIND 区域文件生成、SOA 序列号、记录差异。内容必须是 validateContent 通过的规范化结构。

const crypto = require('crypto');

// 规范化 JSON（键排序），用于内容指纹与不变性存储
function canonicalJSON(obj) {
  return JSON.stringify(sort(obj));
}
function sort(v) {
  if (Array.isArray(v)) return v.map(sort);
  if (v && typeof v === 'object') {
    return Object.keys(v).sort().reduce((o, k) => { o[k] = sort(v[k]); return o; }, {});
  }
  return v;
}
function contentHash(content) {
  return crypto.createHash('sha256').update(canonicalJSON(content)).digest('hex');
}

// YYYYMMDDnn 风格序列号：同日序号递增，且始终大于所有已发布序列号（回滚也产生更大值）
function nextSerial(latestSerial, now = new Date()) {
  const y = now.getUTCFullYear();
  const m = String(now.getUTCMonth() + 1).padStart(2, '0');
  const d = String(now.getUTCDate()).padStart(2, '0');
  const base = Number(`${y}${m}${d}00`);
  const candidate = Math.max(base, (latestSerial || 0) + 1);
  if (candidate > 4294967295) throw new Error('SOA 序列号已达 32 位上限');
  return candidate;
}

const TYPE_ORDER = { NS: 0, A: 1, AAAA: 2, CNAME: 3, MX: 4, TXT: 5 };

// 区域头中的 rname 已在验证阶段编码（local 中的 . 已转义）
function renderZoneFile(content, serial) {
  const lines = [];
  const origin = content.zoneName.endsWith('.') ? content.zoneName : content.zoneName + '.';
  lines.push(`; BIND zone file for ${origin}`);
  lines.push(`; generated by DNS Zone Console, serial ${serial}`);
  lines.push(`$ORIGIN ${origin}`);
  lines.push(`$TTL 3600`);
  lines.push('');
  lines.push(
    `@ IN SOA ${content.mname} ${content.rname} (` +
    ` ${serial} ; serial` +
    ` 7200       ; refresh` +
    ` 3600       ; retry` +
    ` 1209600    ; expire` +
    ` 3600 )     ; minimum`
  );
  lines.push('');

  const records = content.records.slice().sort((a, b) => {
    if (a.name !== b.name) return a.name < b.name ? -1 : 1;
    const ta = TYPE_ORDER[a.type], tb = TYPE_ORDER[b.type];
    if (ta !== tb) return ta - tb;
    const pa = a.priority == null ? 0 : a.priority;
    const pb = b.priority == null ? 0 : b.priority;
    if (pa !== pb) return pa - pb;
    return String(a.value) < String(b.value) ? -1 : 1;
  });

  let lastName = null;
  for (const r of records) {
    const owner = lastName === r.name ? '' : r.name;
    lastName = r.name;
    const ownerCol = (owner + '                 ').slice(0, 17);
    let rdata;
    switch (r.type) {
      case 'MX': rdata = `MX ${r.priority} ${r.value}`; break;
      case 'TXT': rdata = `TXT ${renderTXT(r.value)}`; break;
      default: rdata = `${r.type} ${r.value}`;
    }
    lines.push(`${ownerCol}${r.ttl}\tIN\t${rdata}`);
  }
  lines.push('');
  return lines.join('\n');
}

// TXT：按 UTF-8 码点切成 <=255 字节的字符串块；反斜杠与引号转义
function renderTXT(text) {
  const escaped = text.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  const chunks = [];
  let buf = '';
  let bytes = 0;
  for (const ch of escaped) {
    const len = Buffer.byteLength(ch, 'utf8');
    if (bytes + len > 255) { chunks.push(buf); buf = ''; bytes = 0; }
    buf += ch;
    bytes += len;
  }
  if (buf || chunks.length === 0) chunks.push(buf);
  return chunks.map((c) => `"${c}"`).join(' ');
}

// key 不含 id；TTL 不同视为变更（移除+新增）
function recordKey(r) {
  return [
    (r.name || '').toLowerCase(),
    (r.type || '').toUpperCase(),
    r.type === 'MX' ? r.priority : '',
    r.value,
    r.ttl
  ].join('|');
}

// 比较两份内容（best-effort：未通过验证时记录可能缺规范化值，仍尽量展示）
function diffContent(fromContent, toContent) {
  const from = fromContent ? (fromContent.records || []) : [];
  const to = toContent ? (toContent.records || []) : [];

  const norm = (r) => ({
    name: r.name || '',
    type: (r.type || '').toUpperCase(),
    ttl: Number(r.ttl) || null,
    value: r.value == null ? '' : String(r.value),
    priority: r.priority == null ? null : Number(r.priority)
  });
  const fromRecs = from.map(norm);
  const toRecs = to.map(norm);

  const fromMap = new Map();
  for (const r of fromRecs) {
    const k = recordKey(r);
    fromMap.set(k, (fromMap.get(k) || 0) + 1);
  }
  const toMap = new Map();
  for (const r of toRecs) {
    const k = recordKey(r);
    toMap.set(k, (toMap.get(k) || 0) + 1);
  }

  const added = [];
  const removed = [];
  for (const r of toRecs) {
    const k = recordKey(r);
    if (fromMap.has(k)) {
      fromMap.set(k, fromMap.get(k) - 1);
      if (fromMap.get(k) === 0) fromMap.delete(k);
    } else added.push(r);
  }
  for (const r of fromRecs) {
    const k = recordKey(r);
    if (toMap.has(k)) {
      toMap.set(k, toMap.get(k) - 1);
      if (toMap.get(k) === 0) toMap.delete(k);
    } else removed.push(r);
  }

  const header = [];
  const fields = [['zoneName', '区域名'], ['mname', '主 DNS'], ['rname', '管理员邮箱']];
  for (const [key, label] of fields) {
    const a = fromContent ? fromContent[key] : undefined;
    const b = toContent ? toContent[key] : undefined;
    if ((a || '') !== (b || '')) header.push({ field: key, label, from: a || '', to: b || '' });
  }

  return {
    header,
    added,
    removed,
    hasChanges: added.length > 0 || removed.length > 0 || header.length > 0,
    fromExists: !!fromContent
  };
}

module.exports = { canonicalJSON, contentHash, nextSerial, renderZoneFile, diffContent, recordKey };
